// Runs every suite and writes docs/test-report.md from the real results, so the numbers in the
// README can be checked instead of trusted.
//   npm run test:report              (unit + chain + e2e; reads the last mutation run if there is one)
import { execSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"

const tmp = "scratch/report"
mkdirSync(tmp, { recursive: true })
const run = (cmd: string, env: Record<string, string> = {}) => {
  try {
    execSync(cmd, { stdio: "inherit", env: { ...process.env, ...env } })
  } catch {
    /* failures are counted from the json, not the exit code */
  }
}

type VitestJson = { numTotalTests: number; numPassedTests: number; numFailedTests: number; testResults: { name: string; assertionResults: { fullName: string; status: string }[] }[] }
function vitest(label: string, config: string): { label: string; total: number; passed: number; failed: string[]; files: [string, number][] } {
  const out = `${tmp}/${label}.json`
  run(`npx vitest run ${config} --reporter=json --outputFile=${out}`)
  const r = JSON.parse(readFileSync(out, "utf8")) as VitestJson
  return {
    label,
    total: r.numTotalTests,
    passed: r.numPassedTests,
    failed: r.testResults.flatMap((f) => f.assertionResults.filter((a) => a.status === "failed").map((a) => a.fullName)),
    files: r.testResults.map((f) => [f.name.replace(/\\/g, "/").replace(/^.*\/test\//, "test/"), f.assertionResults.length]),
  }
}

type PwSuite = { title: string; specs?: { title: string; tests: { projectName: string; results: { status: string }[] }[] }[]; suites?: PwSuite[] }
function e2e() {
  const out = `${tmp}/e2e.json`
  run("npm run build")
  run("npx playwright test --reporter=json", { PLAYWRIGHT_JSON_OUTPUT_NAME: out })
  const r = JSON.parse(readFileSync(out, "utf8")) as { suites: PwSuite[] }
  const rows: { file: string; title: string; project: string; status: string }[] = []
  const walk = (s: PwSuite, file: string, path: string[]) => {
    const title = (t: string) => [...path, t].join(" › ")
    for (const spec of s.specs ?? []) for (const t of spec.tests) rows.push({ file, title: title(spec.title), project: t.projectName, status: t.results.at(-1)?.status ?? "skipped" })
    for (const c of s.suites ?? []) walk(c, file, [...path, c.title])
  }
  for (const s of r.suites) walk(s, s.title, [])
  return rows
}

function mutation() {
  const p = "reports/mutation/mutation.json"
  if (!existsSync(p)) return null
  const r = JSON.parse(readFileSync(p, "utf8")) as { files: Record<string, { mutants: { status: string }[] }> }
  return Object.entries(r.files).map(([file, f]) => {
    const killed = f.mutants.filter((m) => m.status === "Killed" || m.status === "Timeout").length
    const survived = f.mutants.filter((m) => m.status === "Survived").length
    return { file, total: f.mutants.length, killed, survived }
  })
}

const unit = vitest("unit", "")
const chain = vitest("chain", "--config vitest.chain.config.ts")
const browser = e2e()
const mut = mutation()

const pct = (a: number, b: number) => (b ? ((100 * a) / b).toFixed(1) : "0")
const e2ePassed = browser.filter((t) => t.status === "passed").length
const lines = [
  "# Test report",
  "",
  `Generated by \`npm run test:report\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC, commit \`${execSync("git rev-parse --short HEAD").toString().trim()}\`, Node ${process.version}, ${process.platform}.`,
  "",
  "| Suite | Passed | What it runs against |",
  "|---|---|---|",
  `| Unit (\`npm test\`) | **${unit.passed}/${unit.total}** | pure logic, the API handlers, translations, parity between the app, \`verify.mjs\` and \`check.html\` |`,
  `| Chain (\`npm run test:chain\`) | **${chain.passed}/${chain.total}** | live Tiramisu testnet: the demo records, the read proxy, the drip |`,
  `| Browser (\`npm run test:e2e\`) | **${e2ePassed}/${browser.length}** | Chrome, desktop and phone, every page in light/dark × English/Hindi, with an axe accessibility audit |`,
  ...(mut ? [`| Mutation (\`npm run test:mutation\`) | **${pct(mut.reduce((a, m) => a + m.killed, 0), mut.reduce((a, m) => a + m.total, 0))}%** killed | bugs planted in the verdict logic by Stryker |`] : []),
  "",
]
const fails = [...unit.failed.map((f) => `unit: ${f}`), ...chain.failed.map((f) => `chain: ${f}`), ...browser.filter((t) => t.status !== "passed").map((t) => `e2e [${t.project}]: ${t.title} (${t.status})`)]
lines.push(fails.length ? `## Failures\n\n${fails.map((f) => `- ${f}`).join("\n")}\n` : "No failures.\n")
lines.push("## Unit and chain tests by file\n", "| File | Tests |", "|---|---|", ...[...unit.files, ...chain.files].map(([f, n]) => `| \`${f}\` | ${n} |`), "")
lines.push("## Browser tests\n", "| Test | Desktop | Phone |", "|---|---|---|")
for (const title of [...new Set(browser.map((t) => t.title))]) {
  const s = (p: string) => (browser.find((t) => t.title === title && t.project === p)?.status === "passed" ? "pass" : (browser.find((t) => t.title === title && t.project === p)?.status ?? "-"))
  lines.push(`| ${title.replace(/\|/g, "\\|")} | ${s("desktop")} | ${s("phone")} |`)
}
if (mut) {
  lines.push("", "## Mutation testing\n", "| File | Mutants | Killed | Survived |", "|---|---|---|---|", ...mut.map((m) => `| \`${m.file}\` | ${m.total} | ${m.killed} | ${m.survived} |`))
  lines.push("", "Survivors are listed in `reports/mutation/mutation.html` after a run; the ones left are equivalent (for example, a fallback empty list replaced with a junk string that can never match a real hash).")
}
writeFileSync("docs/test-report.md", lines.join("\n") + "\n")
console.log(`docs/test-report.md: unit ${unit.passed}/${unit.total}, chain ${chain.passed}/${chain.total}, e2e ${e2ePassed}/${browser.length}`)
